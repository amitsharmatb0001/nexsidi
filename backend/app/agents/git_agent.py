@dataclass(slots=True)
class GitRepoConfig:
    """Configuration for a new repository."""

    name: str
    description: str = ""
    provider: GitProvider = GitProvider.GITHUB
    visibility: RepoVisibility = RepoVisibility.PRIVATE
    default_branch: str = "main"
    auto_init: bool = False
    gitignore_template: str = ""

    @classmethod
    def from_contract(cls, contract: dict[str, Any]) -> GitRepoConfig:
        """Create repo config from architecture contract."""
        project_name = contract.get("project_name", "project")
        # Sanitize for repo naming: lowercase, hyphens, no special chars
        repo_name = re.sub(r"[^a-z0-9-]", "-", project_name.lower())[:100]
        repo_name = re.sub(r"-+", "-", repo_name).strip("-")

        return cls(
            name=repo_name,
            description=f"Generated by NexSidi: {project_name}",
            visibility=RepoVisibility.PRIVATE,
        )


@dataclass(slots=True)
class GitOperationResult:
    """Result of a Git operation."""

    operation: GitOperationType
    status: GitOperationStatus
    repo_url: str = ""
    branch: str = ""
    pr_url: str = ""
    pr_number: int = 0
    commit_sha: str = ""
    files_pushed: int = 0
    error: str = ""
    # True when GITHUB_TOKEN was absent and the operation was simulated.
    is_simulation: bool = False

    def to_dict(self) -> dict[str, Any]:
        return {
            "operation": self.operation.value,
            "status": self.status.value,
            "repo_url": self.repo_url,
            "branch": self.branch,
            "pr_url": self.pr_url,
            "pr_number": self.pr_number,
            "commit_sha": self.commit_sha,
            "files_pushed": self.files_pushed,
            "error": self.error,
        }


@dataclass(slots=True)

class GitAgent:
    """Git Agent -- manages source code repositories.

    Handles repo creation, code push, branching, and PRs
    after NexSidi generates a project.
    """

    name = "git_agent"
    display_name = "Git Agent"
    default_complexity = TaskComplexity.MEDIUM
    default_model: str | None = None

    @property
    def tools(self) -> list:
        """Web search tools for looking up Git/GitHub API docs."""
        return [WEB_SEARCH_TOOL, WEB_SCRAPE_TOOL]

    async def run(
        self,
        pipeline_run_id: str,
        context: dict[str, Any],
    ) -> AgentResult:
        """Execute with timing, logging, and error handling."""
        return await run_agent(self, pipeline_run_id, context)

    async def execute(
        self,
        pipeline_run_id: str,
        context: dict[str, Any],
    ) -> AgentResult:
        """Execute Git operations for a completed pipeline.

        Steps:
        1. Create repo from contract config
        2. Push backend + frontend code
        3. Create PR with structured description
        """
        # Check inbox for messages from other agents (esp. AUTHORITY directives)
        inbox_messages = await check_inbox(self.name, pipeline_run_id)
        inbox_context = format_inbox_for_prompt(inbox_messages)

        contract = context.get("vikram", {}).get("contract", {})
        if not contract:
            return AgentResult(
                agent_name=self.name,
                status=AgentStatus.COMPLETED,
                output={"status": "skipped", "reason": "No architecture contract"},
            )

        repo_config = GitRepoConfig.from_contract(contract)

        # Collect files from pipeline context
        backend_files = _collect_files(context, "shubham")
        frontend_files = _collect_files(context, "aanya")
        total_files = len(backend_files) + len(frontend_files)

        if total_files == 0:
            return AgentResult(
                agent_name=self.name,
                status=AgentStatus.COMPLETED,
                output={"status": "skipped", "reason": "No generated files to push"},
            )

        # Create repo
        create_result = await self._create_repo(repo_config)

        # Push code
        push_result = await self._push_code(
            repo_url=create_result.repo_url,
            backend_files=backend_files,
            frontend_files=frontend_files,
        )

        # Create PR
        pr_result = await self._create_pr(
            repo_url=create_result.repo_url,
            pipeline_run_id=pipeline_run_id,
            context=context,
            files_pushed=push_result.files_pushed,
        )

        # is_simulation_git is True if ANY operation was simulated.
        is_simulation_git = (
            create_result.is_simulation
            or push_result.is_simulation
            or pr_result.is_simulation
        )
        output = {
            "repo_url": create_result.repo_url,
            "repo_name": repo_config.name,
            "provider": repo_config.provider.value,
            "branch": push_result.branch,
            "commit_sha": push_result.commit_sha,
            "files_pushed": push_result.files_pushed,
            "pr_url": pr_result.pr_url,
            "pr_number": pr_result.pr_number,
            # Honest reporting: True when no real GitHub API calls were made.
            "is_simulation_git": is_simulation_git,
            "operations": [
                create_result.to_dict(),
                push_result.to_dict(),
                pr_result.to_dict(),
            ],
        }

        logger.info(
            "git_operations_complete",
            repo=repo_config.name,
            files=push_result.files_pushed,
            pr=pr_result.pr_number,
        )

        # STORE-FIX: Persist output to context engine for downstream agents
        await store_output(self, pipeline_run_id, output)

        return AgentResult(
            agent_name=self.name,
            status=AgentStatus.COMPLETED,
            output=output,
        )

    # -- GitHub REST API helper -----------------------------------------------

    @staticmethod
    def _parse_owner_repo(repo_url: str) -> tuple[str, str]:
        """Extract owner and repo name from a GitHub URL.  # GIT-FIX

        Handles both https://github.com/owner/repo and owner/repo formats.
        """
        url = repo_url.rstrip("/")
        if "github.com/" in url:
            parts = url.split("github.com/", 1)[1].split("/")
        elif "gitlab.com/" in url:
            parts = url.split("gitlab.com/", 1)[1].split("/")
        else:
            parts = url.split("/")
        owner = parts[0] if parts else "nexsidi"
        repo = parts[1].removesuffix(".git") if len(parts) > 1 else "project"
        return owner, repo

    @staticmethod
    async def _github_api(  # GIT-FIX
        method: str,
        path: str,
        token: str,
        *,
        json: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        """Make a GitHub REST API request.  # GIT-FIX

        Returns parsed JSON on success (2xx). Raises RuntimeError on failure.
        """
        headers = {
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
        }
        async with httpx.AsyncClient(timeout=30.0) as client:
            resp = await client.request(
                method,
                f"{_get_github_api_base()}{path}",
                headers=headers,
                json=json,
            )
        if resp.status_code >= 400:
            raise RuntimeError(
                f"GitHub API {method} {path} returned {resp.status_code}: "
                f"{resp.text[:200]}"
            )
        if resp.status_code == 204:
            return {}
        return resp.json()

    # -- Repo operations -------------------------------------------------------

    async def _create_repo(self, config: GitRepoConfig) -> GitOperationResult:  # GIT-FIX
        """Create a new repository via GitHub REST API.  # GIT-FIX

        Falls back to URL generation if no GITHUB_TOKEN is available.
        """
        import os

        token = os.environ.get("GITHUB_TOKEN", "")
        logger.info(
            "git_create_repo",
            provider=config.provider.value,
            name=config.name,
            visibility=config.visibility.value,
            has_token=bool(token),
        )

        if token and config.provider == GitProvider.GITHUB:
            try:
                data = await self._github_api(
                    "POST",
                    "/user/repos",
                    token,
                    json={
                        "name": config.name,
                        "description": config.description,
                        "private": config.visibility == RepoVisibility.PRIVATE,
                        "auto_init": True,
                    },
                )
                repo_url = data.get("html_url", f"https://github.com/nexsidi/{config.name}")
                logger.info("git_repo_created", repo_url=repo_url)
                return GitOperationResult(
                    operation=GitOperationType.CREATE_REPO,
                    status=GitOperationStatus.COMPLETED,
                    repo_url=repo_url,
                )
            except RuntimeError as exc:
                logger.warning("git_create_repo_api_error", error=str(exc)[:200])

        # Fallback: generate expected URL without API call (simulated)
        repo_url = f"https://{config.provider.value}.com/nexsidi/{config.name}"
        logger.warning("git_create_repo_simulated", reason="No GITHUB_TOKEN or unsupported provider")
        return GitOperationResult(
            operation=GitOperationType.CREATE_REPO,
            status=GitOperationStatus.COMPLETED,
            repo_url=repo_url,
            is_simulation=True,
        )

    async def _push_code(  # GIT-FIX
        self,
        repo_url: str,
        backend_files: dict[str, str],
        frontend_files: dict[str, str],
    ) -> GitOperationResult:
        """Push generated code via GitHub Contents API.  # GIT-FIX

        Uses PUT /repos/{owner}/{repo}/contents/{path} for each file.
        Falls back to simulated SHA when GITHUB_TOKEN is absent.
        """
        import os

        token = os.environ.get("GITHUB_TOKEN", "")
        all_files = {**backend_files, **frontend_files}
        total = len(all_files)

        logger.info(
            "git_push_code",
            repo=repo_url,
            total_files=total,
            has_token=bool(token),
        )

        if token and "github.com" in repo_url:
            owner, repo = self._parse_owner_repo(repo_url)
            feature_branch = "nexsidi/generated"
            try:
                # AUDIT-FIX: Use Git Trees API for atomic batch push.
                # Old approach: 1 PUT per file = 100-200 HTTP calls for 50-100 files.
                # New approach: N blob creates + 1 tree + 1 commit + 1 ref = N+3 calls.
                # Also atomic — all files appear in a single commit.

                # Step 1: Get base commit SHA from main
                ref_data = await self._github_api(
                    "GET", f"/repos/{owner}/{repo}/git/ref/heads/main", token
                )
                base_sha = ref_data.get("object", {}).get("sha", "")

                # Step 2: Create blobs for each file
                tree_items: list[dict[str, str]] = []
                for path, content_str in all_files.items():
                    safe_path = path.lstrip("/")
                    blob = await self._github_api(
                        "POST",
                        f"/repos/{owner}/{repo}/git/blobs",
                        token,
                        json={
                            "content": base64.b64encode(
                                content_str.encode("utf-8")
                            ).decode("ascii"),
                            "encoding": "base64",
                        },
                    )
                    tree_items.append({
                        "path": safe_path,
                        "mode": "100644",
                        "type": "blob",
                        "sha": blob["sha"],
                    })

                # Step 3: Create tree from blobs (based on main's tree)
                base_commit = await self._github_api(
                    "GET", f"/repos/{owner}/{repo}/git/commits/{base_sha}", token
                )
                base_tree_sha = base_commit.get("tree", {}).get("sha", "")

                tree = await self._github_api(
                    "POST",
                    f"/repos/{owner}/{repo}/git/trees",
                    token,
                    json={"base_tree": base_tree_sha, "tree": tree_items},
                )

                # Step 4: Create commit pointing to the new tree
                commit = await self._github_api(
                    "POST",
                    f"/repos/{owner}/{repo}/git/commits",
                    token,
                    json={
                        "message": f"feat: NexSidi generated project ({len(all_files)} files)",
                        "tree": tree["sha"],
                        "parents": [base_sha],
                    },
                )
                commit_sha = commit["sha"]

                # Step 5: Create or update feature branch ref
                try:
                    await self._github_api(
                        "POST",
                        f"/repos/{owner}/{repo}/git/refs",
                        token,
                        json={"ref": f"refs/heads/{feature_branch}", "sha": commit_sha},
                    )
                except RuntimeError:
                    # Branch exists — update it
                    await self._github_api(
                        "PATCH",
                        f"/repos/{owner}/{repo}/git/refs/heads/{feature_branch}",
                        token,
                        json={"sha": commit_sha, "force": True},
                    )

                logger.info("git_code_pushed", repo=repo_url, branch=feature_branch, files_pushed=len(all_files))
                return GitOperationResult(
                    operation=GitOperationType.PUSH_CODE,
                    status=GitOperationStatus.COMPLETED,
                    repo_url=repo_url,
                    branch=feature_branch,
                    commit_sha=commit_sha,
                    files_pushed=len(all_files),
                )
            except RuntimeError as exc:
                logger.warning("git_push_api_error", error=str(exc)[:200])

        # Fallback: simulated SHA (no token or non-GitHub provider)
        logger.warning("git_push_simulated", reason="No GITHUB_TOKEN or unsupported provider", files=total)
        return GitOperationResult(
            operation=GitOperationType.PUSH_CODE,
            status=GitOperationStatus.COMPLETED,
            repo_url=repo_url,
            branch="main",
            commit_sha=secrets.token_hex(20),
            files_pushed=total,
            is_simulation=True,
        )

    async def _create_pr(  # GIT-FIX
        self,
        repo_url: str,
        pipeline_run_id: str,
        context: dict[str, Any],
        files_pushed: int,
    ) -> GitOperationResult:
        """Create a pull request via GitHub REST API.  # GIT-FIX

        Falls back to simulated PR number when GITHUB_TOKEN is absent.
        """
        import os

        token = os.environ.get("GITHUB_TOKEN", "")
        contract = context.get("vikram", {}).get("contract", {})
        project_name = contract.get("project_name", "project")

        karan = context.get("karan", {})
        navya = context.get("navya", {})
        deepika = context.get("deepika", {})
        aarav = context.get("aarav", {})
        pranav = context.get("pranav", {})

        pr_body = PR_TEMPLATE.format(
            pipeline_run_id=pipeline_run_id,
            project_name=project_name,
            backend_files=len(_collect_files(context, "shubham")),
            backend_lang=contract.get("tech_stack", {}).get("backend", "Python/FastAPI"),
            frontend_files=len(_collect_files(context, "aanya")),
            frontend_lang=contract.get("tech_stack", {}).get("frontend", "Next.js"),
            report_count=sum(1 for x in [karan, navya, deepika, aarav] if x),
            security_status="passed" if karan else "N/A",
            logic_status="passed" if navya else "N/A",
            perf_status="passed" if deepika else "N/A",
            test_status="passed" if aarav else "N/A",
            deploy_provider=pranav.get("provider", "N/A") if isinstance(pranav, dict) else "N/A",
            deploy_url=pranav.get("deployment_url", "N/A") if isinstance(pranav, dict) else "N/A",
        )

        logger.info("git_create_pr", repo=repo_url, has_token=bool(token))

        if token and "github.com" in repo_url:
            owner, repo = self._parse_owner_repo(repo_url)
            try:
                # AUDIT-FIX: Branch is already created by _push_code. No need
                # to create it again here — _push_code now pushes to the
                # feature branch directly, so the PR will show a real diff.
                branch_name = "nexsidi/generated"

                pr_data = await self._github_api(
                    "POST",
                    f"/repos/{owner}/{repo}/pulls",
                    token,
                    json={
                        "title": f"feat: NexSidi generated project — {project_name}",
                        "body": pr_body,
                        "head": branch_name,
                        "base": "main",
                    },
                )
                pr_number = pr_data.get("number", 0)
                pr_url = pr_data.get("html_url", f"{repo_url}/pull/{pr_number}")
                logger.info("git_pr_created", repo=repo_url, pr_number=pr_number)
                return GitOperationResult(
                    operation=GitOperationType.CREATE_PR,
                    status=GitOperationStatus.COMPLETED,
                    repo_url=repo_url,
                    branch=branch_name,
                    pr_url=pr_url,
                    pr_number=pr_number,
                )
            except RuntimeError as exc:
                logger.warning("git_create_pr_api_error", error=str(exc)[:200])

        # Fallback: simulated PR number
        # Fallback: simulated PR (no token or unsupported provider)
        pr_number = secrets.randbelow(9000) + 1000
        logger.warning("git_pr_simulated", reason="No GITHUB_TOKEN or unsupported provider")
        return GitOperationResult(
            operation=GitOperationType.CREATE_PR,
            status=GitOperationStatus.COMPLETED,
            repo_url=repo_url,
            branch="nexsidi/generated",
            pr_url=f"{repo_url}/pull/{pr_number}",
            pr_number=pr_number,
            is_simulation=True,
        )

    async def commit_files(  # GIT-FIX
        self,
        repo_url: str,
        token: str,
        files: dict[str, str],
        message: str,
        branch: str = "main",
    ) -> None:
        """Commit files to a repository via GitHub Contents API.  # GIT-FIX

        Called by pipeline.py during pipeline execution to persist
        generated code to the repository incrementally.

        Uses PUT /repos/{owner}/{repo}/contents/{path} for each file.
        If the repo is not a GitHub URL or token is empty, logs a warning
        and returns without error (graceful degradation).
        """
        if not token or "github.com" not in repo_url:
            logger.warning(
                "git_commit_files_skipped",
                repo=repo_url,
                has_token=bool(token),
                reason="No GitHub token or non-GitHub repo",
            )
            return

        owner, repo = self._parse_owner_repo(repo_url)
        committed = 0

        for path, content_str in files.items():
            safe_path = path.lstrip("/")
            b64_content = base64.b64encode(
                content_str.encode("utf-8")
            ).decode("ascii")

            # Check if file already exists (need its SHA to update)
            existing_sha: str | None = None
            try:
                existing = await self._github_api(
                    "GET",
                    f"/repos/{owner}/{repo}/contents/{safe_path}",
                    token,
                )
                existing_sha = existing.get("sha")
            except RuntimeError:
                pass  # File doesn't exist yet

            payload: dict[str, Any] = {
                "message": message,
                "content": b64_content,
                "branch": branch,
            }
            if existing_sha:
                payload["sha"] = existing_sha

            try:
                await self._github_api(
                    "PUT",
                    f"/repos/{owner}/{repo}/contents/{safe_path}",
                    token,
                    json=payload,
                )
                committed += 1
            except RuntimeError as exc:
                logger.warning(
                    "git_commit_file_error",
                    path=safe_path,
                    error=str(exc)[:200],
                )

        logger.info(
            "git_commit_files_done",
            repo=repo_url,
            branch=branch,
            committed=committed,
            total=len(files),
        )

    def generate_gitignore(self, contract: dict[str, Any]) -> str:
        """Generate a .gitignore tailored to the project's tech stack."""
        tech = contract.get("tech_stack", {})
        lines = [DEFAULT_GITIGNORE]

        backend = tech.get("backend", "")
        if "django" in backend.lower():
            lines.append("# Django\ndb.sqlite3\nmedia/\nstaticfiles/\n")
        if "fastapi" in backend.lower() or "flask" in backend.lower():
            lines.append("# Python API\n*.pid\n")

        frontend = tech.get("frontend", "")
        if "next" in frontend.lower():
            lines.append("# Next.js\n.next/\nout/\n")
        if "react" in frontend.lower() and "next" not in frontend.lower():
            lines.append("# React\nbuild/\n")

        return "\n".join(lines)


def _collect_files(context: dict[str, Any], agent_key: str) -> dict[str, str]:
    """Collect file_contents from an agent's pipeline output."""
    output = context.get(agent_key, {})
    if isinstance(output, dict):
        return output.get("file_contents", {})
    return {}


