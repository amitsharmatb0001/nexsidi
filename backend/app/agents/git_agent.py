"""Git Agent: manages source code repositories after project generation.

Handles the DELIVERY stage's repository operations:
1. Creates a new GitHub/GitLab repository
2. Pushes generated code (backend + frontend)
3. Creates feature branches for code review
4. Opens pull requests with structured descriptions
5. Manages .gitignore and repository settings

Token Security (AUDIT FIX #19):
- GitHub tokens stored in-memory only (encrypted per-session key)
- Token destroyed immediately after clone/push completes
- Token NEVER written to disk or database
- Token NEVER logged — audit log records only repo URL + timestamp
- Token scoped to minimum required permissions (repo read/write)
- Failed operations: 1 retry within 5-minute timeout, then token destroyed
"""

